"""Pure requirement-aware feasible-action projection helpers.

This module deliberately does not score actions, mutate SafeLinUCB, or inspect
ground truth.  It consumes the original selector scores and already-computed
feasibility facts, then either keeps the selected action or projects it onto a
requirement-closing action.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from math import inf, isfinite
from typing import Any, Callable, Iterable, Mapping, Sequence, TypeVar


_PRODUCT_ALIASES: dict[str, str] = {
    "": "none",
    "none": "none",
    "empty": "none",
    "defer": "none",
    "delay": "none",
    "delay_store": "none",
    "metadata": "metadata",
    "meta": "metadata",
    "alert": "metadata",
    "roi": "roi",
    "verification": "roi",
    "verify": "roi",
    "roi_context": "roi_context",
    "roi+context": "roi_context",
    "roi-context": "roi_context",
    "roi context": "roi_context",
    "context": "roi_context",
    "evidence": "roi_context",
    "full": "roi_context",
}

_PRODUCT_RANK: dict[str, int] = {
    "none": 0,
    "metadata": 1,
    "roi": 2,
    "roi_context": 3,
}

_RANK_PRODUCT: dict[int, str] = {rank: product for product, rank in _PRODUCT_RANK.items()}


def normalize_product(product: Any) -> str:
    """Normalize evaluator-compatible product and requirement aliases."""

    value = str(product or "").strip().lower()
    return _PRODUCT_ALIASES.get(value, value)


def immediate_product(payload_policy: Any) -> str:
    """Return the product generated by the current action, not a later residual."""

    value = str(payload_policy or "").strip().lower()
    if "_then_" in value:
        value = value.split("_then_", 1)[0]
    return normalize_product(value)


def product_rank(product: Any) -> int:
    """Rank products using the public evaluator's alert/verification/evidence order."""

    return _PRODUCT_RANK.get(normalize_product(product), -1)


def product_satisfies(product: Any, required_product: Any) -> bool:
    """Return whether one delivered product closes the requested product level."""

    required_rank = product_rank(required_product)
    observed_rank = product_rank(product)
    return required_rank > 0 and observed_rank >= required_rank


def delivered_products_satisfy(delivered_products: Iterable[Any], required_product: Any) -> bool:
    """Match the public evaluator's set-based closure semantics."""

    return any(product_satisfies(product, required_product) for product in delivered_products)


def highest_delivered_product(delivered_products: Iterable[Any]) -> str:
    """Return the highest canonical delivered product, or an empty string."""

    best_rank = max((product_rank(product) for product in delivered_products), default=0)
    return "" if best_rank <= 0 else _RANK_PRODUCT[best_rank]


def residual_required_product(required_product: Any, delivered_products: Iterable[Any]) -> str:
    """Preserve the original final requirement until it is actually satisfied."""

    requirement = str(required_product or "").strip().lower()
    return "" if delivered_products_satisfy(delivered_products, requirement) else requirement


def closure_credit_due(
    required_product: Any,
    delivered_before: Iterable[Any],
    delivered_after: Iterable[Any],
) -> bool:
    """True only on the first transition into final requirement closure."""

    return (
        not delivered_products_satisfy(delivered_before, required_product)
        and delivered_products_satisfy(delivered_after, required_product)
    )


@dataclass(frozen=True)
class ContactCapacitySlot:
    """A deterministic future downlink-capacity interval."""

    start_s: float
    end_s: float
    rate_mb_s: float


@dataclass(frozen=True)
class GroundArrivalPrediction:
    """Pre-decision compute, queue, contact, and transmission timing."""

    compute_finish_s: float
    queue_service_start_s: float | None
    downlink_start_s: float | None
    ground_arrival_s: float | None
    queue_delay_s: float | None
    transmission_time_s: float | None
    contact_found: bool

    @property
    def finite_ground_arrival_s(self) -> float:
        return self.ground_arrival_s if self.ground_arrival_s is not None else inf


def predict_ground_arrival(
    *,
    current_time_s: float,
    compute_and_encode_s: float,
    backlog_mb: float,
    payload_mb: float,
    contact_slots: Sequence[ContactCapacitySlot],
    deadline_s: float | None = None,
) -> GroundArrivalPrediction:
    """Forecast FIFO-equivalent arrival from compute through future contacts.

    Existing backlog may be served while the new product is being computed.
    Once the product is ready, remaining backlog is conservatively placed ahead
    of it.  No future ground truth or realized delivery result is used.
    """

    ready_s = max(float(current_time_s), float(current_time_s) + max(0.0, float(compute_and_encode_s)))
    backlog_remaining = max(0.0, float(backlog_mb))
    payload_remaining = max(0.0, float(payload_mb))
    if payload_remaining <= 0.0:
        return GroundArrivalPrediction(ready_s, None, None, None, None, None, False)

    queue_service_start: float | None = None
    downlink_start: float | None = None
    total_payload_tx_s = 0.0
    contact_found = False

    for slot in sorted(contact_slots, key=lambda item: (item.start_s, item.end_s)):
        rate = max(0.0, float(slot.rate_mb_s))
        start = max(float(current_time_s), float(slot.start_s))
        end = float(slot.end_s)
        if deadline_s is not None:
            end = min(end, float(deadline_s))
        if rate <= 0.0 or end <= start:
            continue

        # Backlog can drain before the new payload finishes computing.
        before_ready_end = min(end, ready_s)
        if backlog_remaining > 0.0 and before_ready_end > start:
            served = min(backlog_remaining, (before_ready_end - start) * rate)
            backlog_remaining -= served
            start += served / rate
            if backlog_remaining > 1.0e-12:
                continue

        start = max(start, ready_s)
        if end <= start:
            continue
        contact_found = True
        if queue_service_start is None:
            queue_service_start = start

        if backlog_remaining > 0.0:
            served = min(backlog_remaining, (end - start) * rate)
            backlog_remaining -= served
            start += served / rate
            if backlog_remaining > 1.0e-12 or end <= start:
                continue

        if downlink_start is None:
            downlink_start = start
        sent = min(payload_remaining, (end - start) * rate)
        payload_remaining -= sent
        duration = sent / rate
        total_payload_tx_s += duration
        finish_s = start + duration
        if payload_remaining <= 1.0e-12:
            return GroundArrivalPrediction(
                compute_finish_s=ready_s,
                queue_service_start_s=queue_service_start,
                downlink_start_s=downlink_start,
                ground_arrival_s=finish_s,
                queue_delay_s=max(0.0, (downlink_start or finish_s) - ready_s),
                transmission_time_s=total_payload_tx_s,
                contact_found=contact_found,
            )

    return GroundArrivalPrediction(
        compute_finish_s=ready_s,
        queue_service_start_s=queue_service_start,
        downlink_start_s=downlink_start,
        ground_arrival_s=None,
        queue_delay_s=None if downlink_start is None else max(0.0, downlink_start - ready_s),
        transmission_time_s=total_payload_tx_s if total_payload_tx_s > 0.0 else None,
        contact_found=contact_found,
    )


@dataclass(frozen=True)
class ProjectionCandidate:
    """Original-score and feasibility facts for one existing joint action."""

    action: Any
    action_name: str
    model_name: str
    product: str
    original_score: float
    predicted_ground_arrival_s: float | None
    hard_safe: bool
    deadline_feasible: bool
    score_above_defer: bool
    safety_reasons: tuple[str, ...] = ()
    contact_found: bool = True
    eligible_by_existing_filters: bool = True


@dataclass(frozen=True)
class ProjectionResult:
    """Auditable output of the post-selector projection."""

    final_action: Any
    projection_reason: str
    original_action: Any
    requirement_aligned: bool
    direct_closure_feasible: bool
    residual_requirement_after_action: str
    chosen_candidate: ProjectionCandidate | None = None
    mismatch: bool = False
    blocked_reasons: tuple[str, ...] = field(default_factory=tuple)
    progressive_reentry: bool = False
    one_shot_delivery: bool = True
    closure_status_after: str = "planned_closed"


def _candidate_sort_key(candidate: ProjectionCandidate) -> tuple[float, str]:
    return (-float(candidate.original_score), str(candidate.action_name))


def _feasible_candidates(
    candidates: Sequence[ProjectionCandidate],
    predicate: Callable[[ProjectionCandidate], bool],
) -> list[ProjectionCandidate]:
    return [
        candidate
        for candidate in candidates
        if predicate(candidate)
        and candidate.eligible_by_existing_filters
        and candidate.hard_safe
        and candidate.deadline_feasible
        and candidate.score_above_defer
        and candidate.predicted_ground_arrival_s is not None
        and isfinite(float(candidate.predicted_ground_arrival_s))
    ]


def _choose_candidate(
    candidates: Sequence[ProjectionCandidate],
    *,
    selected_model: str,
    prefer_same_model: bool,
    prefer_minimum_satisfying_product: bool,
) -> ProjectionCandidate:
    remaining = list(candidates)
    if prefer_minimum_satisfying_product:
        minimum_rank = min(product_rank(candidate.product) for candidate in remaining)
        remaining = [candidate for candidate in remaining if product_rank(candidate.product) == minimum_rank]
    if prefer_same_model:
        same_model = [candidate for candidate in remaining if candidate.model_name == selected_model]
        if same_model:
            remaining = same_model
    return sorted(remaining, key=_candidate_sort_key)[0]


def _defer_candidate(candidates: Sequence[ProjectionCandidate]) -> ProjectionCandidate | None:
    matches = [
        candidate
        for candidate in candidates
        if (
            normalize_product(candidate.product) == "none"
            or str(candidate.action_name).strip().lower() in {"delay/store", "defer", "delay"}
        )
        and candidate.eligible_by_existing_filters
        and candidate.hard_safe
    ]
    return sorted(matches, key=_candidate_sort_key)[0] if matches else None


def _blocked_reasons(
    candidates: Sequence[ProjectionCandidate],
    residual: str,
) -> tuple[str, ...]:
    blocked: set[str] = set()
    satisfying = [candidate for candidate in candidates if product_satisfies(candidate.product, residual)]
    if not satisfying:
        blocked.add("no_satisfying_action")
    for candidate in satisfying:
        lowered = " ".join(candidate.safety_reasons).lower()
        if not candidate.hard_safe:
            if "battery" in lowered or "soc" in lowered or "energy budget" in lowered:
                blocked.add("soc")
            if "thermal" in lowered:
                blocked.add("thermal")
            if "queue" in lowered:
                blocked.add("queue")
        if not candidate.contact_found:
            blocked.add("no_contact")
        elif not candidate.deadline_feasible:
            blocked.add("deadline")
        if not candidate.score_above_defer:
            blocked.add("negative_score")
    return tuple(sorted(blocked))


def project_requirement_aware_action(
    *,
    selected_action: Any,
    selected_product: Any,
    selected_model: str,
    residual_requirement: Any,
    candidates: Sequence[ProjectionCandidate],
    value_level: str = "high",
    prefer_same_model: bool = True,
    prefer_minimum_satisfying_product: bool = True,
) -> ProjectionResult:
    """Apply the paper policy after the untouched original selector.

    Low/medium tasks are one-shot only: final required product or DEFER.
    High/urgent tasks are direct-final first, then metadata-first progressive
    fallback, then DEFER with the residual retained for later re-evaluation.
    """

    residual = str(residual_requirement or "").strip().lower()
    level = str(value_level or "").strip().lower()
    high_value = level in {"high", "urgent"}
    selected_fact = next(
        (
            candidate
            for candidate in candidates
            if candidate.action is selected_action
            or str(candidate.action_name) == str(getattr(selected_action, "action_name", ""))
        ),
        None,
    )
    selected_direct_feasible = bool(
        selected_fact is not None
        and selected_fact.eligible_by_existing_filters
        and selected_fact.hard_safe
        and selected_fact.deadline_feasible
        and selected_fact.score_above_defer
        and selected_fact.predicted_ground_arrival_s is not None
        and isfinite(float(selected_fact.predicted_ground_arrival_s))
    )
    if not residual or (
        product_satisfies(selected_product, residual)
        and selected_direct_feasible
    ):
        return ProjectionResult(
            final_action=selected_action,
            projection_reason="already_aligned",
            original_action=selected_action,
            requirement_aligned=True,
            direct_closure_feasible=True,
            residual_requirement_after_action="",
            mismatch=False,
            progressive_reentry=False,
            one_shot_delivery=True,
            closure_status_after="planned_closed",
        )

    closure = _feasible_candidates(
        candidates,
        lambda candidate: product_satisfies(candidate.product, residual),
    )
    if closure:
        chosen = _choose_candidate(
            closure,
            selected_model=selected_model,
            prefer_same_model=prefer_same_model,
            prefer_minimum_satisfying_product=prefer_minimum_satisfying_product,
        )
        return ProjectionResult(
            final_action=chosen.action,
            projection_reason="requirement_projected",
            original_action=selected_action,
            requirement_aligned=True,
            direct_closure_feasible=True,
            residual_requirement_after_action="",
            chosen_candidate=chosen,
            mismatch=True,
            progressive_reentry=False,
            one_shot_delivery=True,
            closure_status_after="planned_closed",
        )

    blocked = _blocked_reasons(candidates, residual)
    defer = _defer_candidate(candidates)
    if not high_value:
        return ProjectionResult(
            final_action=selected_action if defer is None else defer.action,
            projection_reason="ordinary_required_product_infeasible",
            original_action=selected_action,
            requirement_aligned=False,
            direct_closure_feasible=False,
            residual_requirement_after_action="",
            chosen_candidate=defer,
            mismatch=True,
            blocked_reasons=blocked,
            progressive_reentry=False,
            one_shot_delivery=True,
            closure_status_after="deferred",
        )

    metadata = _feasible_candidates(
        candidates,
        lambda candidate: normalize_product(candidate.product) == "metadata",
    )
    if metadata:
        chosen = _choose_candidate(
            metadata,
            selected_model=selected_model,
            prefer_same_model=prefer_same_model,
            prefer_minimum_satisfying_product=False,
        )
        return ProjectionResult(
            final_action=chosen.action,
            projection_reason="metadata_first_progressive_fallback",
            original_action=selected_action,
            requirement_aligned=False,
            direct_closure_feasible=False,
            residual_requirement_after_action=residual,
            chosen_candidate=chosen,
            mismatch=True,
            blocked_reasons=blocked,
            progressive_reentry=True,
            one_shot_delivery=False,
            closure_status_after="incomplete",
        )

    return ProjectionResult(
        final_action=selected_action if defer is None else defer.action,
        projection_reason="high_value_defer_recheck",
        original_action=selected_action,
        requirement_aligned=False,
        direct_closure_feasible=False,
        residual_requirement_after_action=residual,
        chosen_candidate=defer,
        mismatch=True,
        blocked_reasons=blocked,
        progressive_reentry=True,
        one_shot_delivery=False,
        closure_status_after="incomplete",
    )


T = TypeVar("T")


def maybe_project_requirement_aware(
    *,
    enabled: bool,
    selected_action: T,
    projector: Callable[[], T],
) -> T:
    """Hard bypass: the projection callable is not invoked when disabled."""

    return projector() if enabled else selected_action


def choose_competing_task(rows: Sequence[Mapping[str, Any]]) -> Mapping[str, Any] | None:
    """Deterministic value/deadline/score tie-break for simultaneously feasible tasks."""

    feasible = [
        row
        for row in rows
        if bool(row.get("hard_safe", False)) and bool(row.get("deadline_feasible", False))
    ]
    if not feasible:
        return None
    return sorted(
        feasible,
        key=lambda row: (
            -float(row.get("effective_task_value", 0.0)),
            float(row.get("remaining_slack_s", inf)),
            -float(row.get("original_score", -inf)),
            str(row.get("task_id", "")),
        ),
    )[0]
